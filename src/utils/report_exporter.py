"""
report_exporter.py
Generates a downloadable structured assessment and checklist report in Markdown format.
Written with clear, human-friendly language for travelers and students.
"""

from datetime import datetime


def generate_markdown_report(assessment_result: dict) -> str:
    rules = assessment_result.get("rules", {})
    ml = assessment_result.get("ml", {})
    consular = assessment_result.get("consular", {})
    country = assessment_result.get("country", "")
    visa_name = assessment_result.get("visa_name", "")
    citizenship = assessment_result.get("citizenship", "")

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        f"# Visa Readiness & Profile Assessment Report",
        f"**Date Generated:** {timestamp}",
        f"**Destination:** {country} | **Visa Category:** {visa_name}",
        f"**Applicant Citizenship:** {citizenship}",
        f"**Governing Rule Standard:** {rules.get('legal_basis', 'N/A')}",
        "",
        "---",
        "",
        "## 1. Assessment Summary",
        f"- **Document & Eligibility Score:** **{rules.get('readiness_score', 0)} / 100** ({rules.get('readiness_level', 'N/A')})",
        f"- **Historical Profile Match:** **{ml.get('probability_percentage', 0)}%** ({ml.get('alignment_tier', 'N/A')})",
        f"- **Official Country Benchmark:** {consular.get('stat_value', 'N/A')} ({consular.get('stat_description', 'N/A')})",
        "",
        "> **Important Notice:** Visa decisions are sovereign government determinations made by immigration officers. No software or consultant can guarantee visa issuance. This report is an analytical review against published requirements.",
        "",
        "---",
        "",
        "## 2. Readiness Breakdown by Category",
    ]

    for dim, score in rules.get("category_scores", {}).items():
        lines.append(f"- **{dim}:** {score}%")

    lines.extend([
        "",
        "---",
        "",
        "## 3. Required Document Checklist",
    ])

    for item in rules.get("checklist", []):
        status = item.get("status", "Check")
        lines.append(f"- [{status}] **{item.get('item', '')}** (Category: {item.get('category', 'General')})")

    if rules.get("missing_documents"):
        lines.extend([
            "",
            "---",
            "",
            "## 4. Missing Information & Action Required",
        ])
        for doc in rules.get("missing_documents"):
            lines.append(f"- [Action Required] {doc}")

    if rules.get("recommendations"):
        lines.extend([
            "",
            "---",
            "",
            "## 5. Personalized Recommendations",
        ])
        for rec in rules.get("recommendations"):
            lines.append(f"- {rec}")

    if rules.get("strengths"):
        lines.extend([
            "",
            "---",
            "",
            "## 6. Profile Strengths",
        ])
        for s in rules.get("strengths"):
            lines.append(f"- {s}")

    lines.extend([
        "",
        "---",
        "",
        "## 7. Historical Profile Data Transparency",
        f"- **Reference Dataset:** {ml.get('dataset_name', 'US Department of Labor OFLC Open Dataset')}",
        f"- **Classification Engine:** Scikit-learn Random Forest Model",
        f"- **Verified Test Accuracy:** {ml.get('model_accuracy', 0.74)*100:.1f}%",
        f"- **Key Profile Drivers:**",
    ])

    for d in ml.get("key_drivers", []):
        lines.append(f"  - {d}")

    lines.append("\n---\n*Report generated by Visa Readiness & Assessment System.*")
    return "\n".join(lines)
